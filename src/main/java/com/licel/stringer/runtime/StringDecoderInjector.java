    public StringDecoderInjector(
            ClassVisitor classVisitor,
            String targetClassName,
            Properties configProperties,
            CryptoContainer cryptoContainer,
            Config config,
            long trialExpirationSeconds,
            byte[] jarExtraFieldTag,
            long integrityKey0,
            long integrityKey1) {
        super(Opcodes.ASM9, classVisitor);
        this.targetClassName = targetClassName;
        this.cryptoContainer = cryptoContainer;
        this.config = config;
        if (trialExpirationSeconds > 0L) {
            this.trialExpirationMillis = trialExpirationSeconds * 1000L;
        }

        this.fieldMappings.put("data", configProperties.getProperty("data"));
        this.fieldMappings.put("lruCache", configProperties.getProperty("lruCache"));
        this.methodMappings.put("shift", configProperties.getProperty("shift"));
        this.methodMappings.put("subWord", configProperties.getProperty("subWord"));
        this.methodMappings.put("decryptString", configProperties.getProperty("decryptString"));
        this.methodMappings.put("calcIntegrityHash", configProperties.getProperty("calcIntegrityHash"));
        this.methodMappings.put("calcStackDepth", configProperties.getProperty("calcStackDepth"));
        this.methodMappings.put("hash24", configProperties.getProperty("hash24"));
        this.methodMappings.put("bootstrap", configProperties.getProperty("bootstrap"));
        this.jarExtraFieldTag = jarExtraFieldTag;
        this.methodMappings.put("initKeys", configProperties.getProperty("initKeys") + cryptoContainer.secureRandom.nextInt(32767));
        this.integrityKey0 = integrityKey0;
        this.integrityKey1 = integrityKey1;
        this.extraClassName = configProperties.getProperty("lruCacheMapClassName");
        this.configProperties = configProperties;
    }

    public String getDecoderClassName() {
        return this.methodMappings.getProperty("decryptString");
    }

    public boolean isEmitFrames() {
        return this.emitFrames;
    }

    @Override
    public void visit(int version, int access, String name, String signature, String superName, String[] interfaces) {
        this.targetClassName = name;
        this.classFileVersion = this.config.getTargetInt() > 0 ? this.config.getTargetInt() : V1_7;
        this.cv.visit(this.classFileVersion, access, name, signature, superName, interfaces);
    }

